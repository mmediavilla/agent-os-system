            // the busy timeout covers the moments it still cannot.
            //
            // **`IMMEDIATE` is the third of the three, and the other two do not
            // work without it.** A `DEFERRED` transaction that reads before it
            // writes takes its read snapshot at the SELECT and asks for the
            // write lock later; if anything has committed in between, SQLite
            // answers `SQLITE_BUSY_SNAPSHOT` and **does not call the busy
            // handler**, because waiting cannot rescue a snapshot that is
            // already stale. So the 5s above is never consulted and the caller
            // gets "database is locked" at once. Measured, 300 read-then-write
            // transactions against a concurrent writer: `DEFERRED` 38 ok / 262
            // locked, failing in ~2ms; `IMMEDIATE` 300 ok / 0 locked, waiting
            // up to 2.5s. `IMMEDIATE` takes the lock at BEGIN, which is what
            // puts the contention back inside the busy timeout's reach.
            //
            // It is not hypothetical: 168 requests died this way over five days
            // of Phase 7-8 verification, 165 of them on the one statement that
            // is *hardest* to see — `RateLimiter::hit()`, which increments a
            // counter in the `cache` table inside exactly this shape of
            // transaction, so a locked row 500s an `/api/agent/*` request that
            // had nothing else wrong with it. `lockForUpdate()` does not save
            // it either: `SQLiteGrammar::compileLock()` returns the empty
            // string, so the SELECT takes no lock at all.
